/**
 * Assigns a quality tier to a brand for ranking and display priority
 */
export function getBrandTier(brand: string): number {
  if (!brand) return 50;
  const b = brand.toLowerCase().trim();

  // 1. OEM / Genuine (Tier 100) - ТОЛЬКО оригинальные бренды Hyundai, Genesis, KIA
  // НИ В КОЕМ СЛУЧАЕ НЕ hy motors, НЕ genuine parts, НЕ китай
  if (b === 'hyundai' || b === 'genesis' || b === 'kia' || b === 'hy/kia') {
    return 100;
  }

  // 2. Premium OEM Tier-1 (Tier 85)
  if (
    /^(mobis|gates|mando|ctr|iljin|valeo|bosch|mahle|elring|victor reinz|hanon|doowon|skf|fag|ina|koyo|nsk|kbc|delphi|ngk|denso|sachs|luk|kyb|kayaba|aisin|brembo)/i.test(b)
  ) {
    return 85;
  }

  // 3. Known Korean Quality Aftermarket (Tier 70)
  if (
    /^(korparts|hi-q|sangsin|partsmall|parts-mall|cardex|car-dex|onnuri|besf1ts|amd|dong yang|dongil|gmb|yuil|kfm|hanse|seoul|thc|phg|yulim|shinhan|shinhwa|geung young|rhee jin|kowoo)/i.test(b)
  ) {
    return 70;
  }

  // 4. Standard Quality Aftermarket (Tier 55)
  // GM, Daewoo, HY Motors (отдельный поставщик/бренд, НЕ Hyundai!)
  if (
    /^(gm|daewoo|hy motors|hymotors|stellox|nsp|patron|febest|kashiyama|trialli|fenox|lynx|miles|lynxauto|metaco|marshall|cga|speedmate)/i.test(b)
  ) {
    return 55;
  }

  // 5. Budget / Low / China (Tier 40)
  if (
    /^(oem|uzdw|uz-daewoo|uz daewoo|uzbek|korwheel|baikor|oscca|daydo|motech|meillor|trt|sib|atc|uxclent|carstation|saul|china|китай|4u|b\/u)/i.test(b)
  ) {
    return 40;
  }

  return 50;
}

/**
 * Resolves a raw counterparty, supplier name, or brand string to its canonical brand name
 */
export function findCanonicalBrand(raw?: string): string | null {
  if (!raw) return null;
  const clean = raw.trim().toLowerCase();
  if (isBrandBlacklisted(clean)) return null;
  return RAW_TO_CANONICAL_BRAND[clean] || null;
}
